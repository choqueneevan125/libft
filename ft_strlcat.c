#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	len_dst;
	size_t	len_src;

	len_src = ft_strlen(src);
	len_dst = 0;
	while (len_dst < size && dst[len_dst] != '\0')
		len_dst++;
	if (len_dst == size)
		return (size + len_src);
	i = 0;
	while (src[i] != '\0' && len_dst + i + 1 < size)
	{
		dst[len_dst + i] = src[i];
		i++;
	}
	dst[len_dst + i] = '\0';
	return (len_dst + len_src);
}
